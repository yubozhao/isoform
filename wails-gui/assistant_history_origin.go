package main

import (
	"bytes"
	"encoding/json"
	"regexp"
	"strings"
)

// Who started a turn in a Claude Code or Codex session.
//
// The person's computer runs many coding agents: side sessions started by
// another session, scheduled hourly prompts, Codex workers run with
// `codex exec` over ssh. Their sessions sit in the same folders as the
// person's own, so without this the history reader learns "how you do things"
// and "about you" from work no person typed. Every prompt is classified where
// it is read:
//
//   - Claude Code stamps each prompt with turnOrigin ("human", "sdk",
//     "task_notification", "scheduled", "peer") and origin.kind. Only "human"
//     is the person. A prompt the desktop app relays from another session
//     ("sdk"), a task notification and a scheduled trigger are agent prompts.
//   - Older transcripts have neither field. Their prompt text is read instead:
//     machine envelopes (<task-notification>, <scheduled-task>, a side
//     session's "Background (from the session that started this one)") are
//     agent prompts, anything else is the person's.
//   - Codex marks the whole session in session_meta: originator codex_exec,
//     source "exec" or a spawned subagent are agent sessions.
//
// Assistant turns belong to the prompt before them, so the reply to an
// hourly check is agent work even inside a session the person also types in.

type historyTurnOrigin int

const (
	historyOriginUnknown historyTurnOrigin = iota
	historyOriginHuman
	historyOriginAgent
)

// historyAgentPromptPrefixes open prompts that a program, not the person,
// wrote. Matched on the prompt text with system reminders removed.
var historyAgentPromptPrefixes = []string{
	"<task-notification",
	"<cross-session-message",
	"<side-sessions-event",
	"<ci-monitor-event",
	"<scheduled-task",
	"<artifact-content-authored",
	"<teammate-message",
}

// historyNeutralPromptPrefixes open lines that are neither a new prompt from
// the person nor from an agent: a compaction summary that continues the work
// in hand, an interruption, a local slash command's echo. They keep the
// origin of the prompt before them.
var historyNeutralPromptPrefixes = []string{
	"this session is being continued from a previous conversation",
	"[request interrupted by user",
	"<command-name>",
	"<command-message>",
	"<local-command-stdout>",
	"<local-command-stderr>",
	"caveat: the messages below were generated by the user while running local commands",
}

// historyAgentPromptMarkers appear anywhere in a side session's first prompt.
var historyAgentPromptMarkers = []string{
	"background (from the session that started this one)",
	"you are a session started from another session",
}

var historySystemReminderRe = regexp.MustCompile(`(?s)<system-reminder>.*?</system-reminder>`)

func historyPromptClean(text string) string {
	return strings.ToLower(strings.TrimSpace(historySystemReminderRe.ReplaceAllString(text, "")))
}

// historyPromptTextIsNeutral reports a line that keeps the current origin.
func historyPromptTextIsNeutral(text string) bool {
	clean := historyPromptClean(text)
	for _, prefix := range historyNeutralPromptPrefixes {
		if strings.HasPrefix(clean, prefix) {
			return true
		}
	}
	return false
}

// historyPromptTextIsAgent reads a prompt without origin fields.
func historyPromptTextIsAgent(text string) bool {
	clean := historyPromptClean(text)
	for _, prefix := range historyAgentPromptPrefixes {
		if strings.HasPrefix(clean, prefix) {
			return true
		}
	}
	for _, marker := range historyAgentPromptMarkers {
		if strings.Contains(clean, marker) {
			return true
		}
	}
	return false
}

// claudeHistoryOriginFields are the per-prompt origin stamps.
type claudeHistoryOriginFields struct {
	TurnOrigin *string `json:"turnOrigin"`
	Origin     *struct {
		Kind string `json:"kind"`
	} `json:"origin"`
}

// claudeHistoryPromptOrigin classifies one Claude Code "user" line. ok is
// false for lines that are not a prompt: tool results, and meta lines with no
// origin stamp. text is the prompt's text blocks.
func claudeHistoryPromptOrigin(line []byte, isMeta bool, content json.RawMessage, text string) (historyTurnOrigin, bool) {
	if claudeHistoryOnlyToolResults(content) || historyPromptTextIsNeutral(text) {
		return historyOriginUnknown, false
	}
	var fields claudeHistoryOriginFields
	_ = json.Unmarshal(line, &fields)
	switch {
	case fields.TurnOrigin != nil && strings.TrimSpace(*fields.TurnOrigin) != "":
		if *fields.TurnOrigin == "human" {
			return historyOriginHuman, true
		}
		return historyOriginAgent, true
	case fields.Origin != nil && strings.TrimSpace(fields.Origin.Kind) != "":
		if fields.Origin.Kind == "human" {
			return historyOriginHuman, true
		}
		return historyOriginAgent, true
	}
	if isMeta || strings.TrimSpace(text) == "" {
		return historyOriginUnknown, false
	}
	if historyPromptTextIsAgent(text) {
		return historyOriginAgent, true
	}
	return historyOriginHuman, true
}

// claudeHistoryOnlyToolResults reports content made only of tool results:
// a tool's output handed back to the model, not a new prompt.
func claudeHistoryOnlyToolResults(raw json.RawMessage) bool {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 || trimmed[0] != '[' {
		return false
	}
	var blocks []struct {
		Type string `json:"type"`
	}
	if json.Unmarshal(trimmed, &blocks) != nil || len(blocks) == 0 {
		return false
	}
	for _, block := range blocks {
		if block.Type != "tool_result" {
			return false
		}
	}
	return true
}

// codexHistoryMetaLine is the session_meta head line's origin part.
type codexHistoryMetaLine struct {
	Type    string `json:"type"`
	Payload struct {
		Originator string          `json:"originator"`
		Source     json.RawMessage `json:"source"`
	} `json:"payload"`
}

// codexHistoryMetaIsAgent reports a Codex session no person drove: one run by
// `codex exec` (workers over ssh, scripts) or spawned as a subagent.
func codexHistoryMetaIsAgent(line []byte) (agent, ok bool) {
	var row codexHistoryMetaLine
	if json.Unmarshal(line, &row) != nil || row.Type != "session_meta" {
		return false, false
	}
	if strings.EqualFold(strings.TrimSpace(row.Payload.Originator), "codex_exec") {
		return true, true
	}
	source := bytes.TrimSpace(row.Payload.Source)
	if len(source) == 0 {
		return false, true
	}
	var name string
	if json.Unmarshal(source, &name) == nil {
		return strings.EqualFold(name, "exec") || strings.EqualFold(name, "subagent"), true
	}
	var object map[string]json.RawMessage
	if json.Unmarshal(source, &object) == nil {
		_, sub := object["subagent"]
		_, exec := object["exec"]
		return sub || exec, true
	}
	return false, true
}

// readAssistantHistorySessionAgent reads a session's head and reports whether
// it was started by an agent: a Codex exec or subagent session, or a Claude
// Code session whose first prompt is not the person's.
func readAssistantHistorySessionAgent(assistant, path string) bool {
	agent := false
	readHistoryHead(path, func(line []byte) string {
		switch assistant {
		case "codex":
			if isAgent, ok := codexHistoryMetaIsAgent(line); ok {
				agent = isAgent
				return "done"
			}
		case "claude":
			var row claudeHistoryTurnLine
			if json.Unmarshal(line, &row) != nil || row.Type != "user" {
				return ""
			}
			origin, ok := claudeHistoryPromptOrigin(line, row.IsMeta, row.Message.Content, claudeHistoryText(row.Message.Content))
			if !ok {
				return ""
			}
			agent = origin == historyOriginAgent
			return "done"
		}
		return ""
	})
	return agent
}
