#!/usr/bin/env node
// Builds website/js/aoy-copy.js, the words of the Agent of You chat on the
// website, from Isoform design's copy.json (v2.1.9). Nothing is written by hand: a
// changed word goes into a new copy.json from design, then this script runs.
// Usage: node scripts/website-aoy-copy.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const source = resolve(repo, 'docs/handoff-2026-11-09/agent-of-you-beta-2.1.9/copy.json');
export const target = resolve(repo, 'website/js/aoy-copy.js');
// Provisional release words (invite list, capacity, a persona agent). Not design's:
// they only add keys under rel.* and never replace a word design wrote.
export const provisional = resolve(repo, 'docs/briefs/agent-of-you-beta/copy-release-provisional.json');

export function build(copy, extra) {
  // The website is English in the first version, whatever the browser's language
  // (v2.1.1, rule 1); the zh-CN chat words are for the app.
  const en = {};
  for (const [key, value] of Object.entries(copy.chat)) en[`chat.${key}`] = value[0]; // [English, zh-CN, where it goes]
  for (const [key, value] of Object.entries(copy.web)) en[`web.${key}`] = value;
  if (extra) {
    for (const [key, value] of Object.entries(extra.release || {})) en[`rel.${key}`] = value;
    for (const [key, value] of Object.entries(extra.persona || {})) {
      if (key.startsWith('_')) continue;
      if (en[key] == null) throw new Error(`persona word for unknown key ${key}`);
      en[`rel.persona.${key}`] = value;
    }
  }
  const body = JSON.stringify({ en }, null, 1);
  const from = extra ? ' and docs/briefs/agent-of-you-beta/copy-release-provisional.json (rel.*, provisional)' : '';
  return `// Generated by scripts/website-aoy-copy.mjs from docs/handoff-2026-11-09/agent-of-you-beta-2.1.9/copy.json${from}. Do not edit.\n(function (root) { root.AoyCopy = ${body}; })(globalThis);\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = build(JSON.parse(readFileSync(source, 'utf8')), JSON.parse(readFileSync(provisional, 'utf8')));
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== next) { console.error('website/js/aoy-copy.js is out of date'); process.exit(1); }
  } else writeFileSync(target, next);
}
