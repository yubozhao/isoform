#!/usr/bin/env node
// Builds website/js/aoy-copy.js, the words of the Agent of You chat on the
// website, from Isoform design's copy.json. Nothing is written by hand: a
// changed word goes into a new copy.json from design, then this script runs.
// Usage: node scripts/website-aoy-copy.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const source = resolve(repo, 'docs/handoff-2026-11-09/agent-of-you-beta-2.0.0/copy.json');
export const target = resolve(repo, 'website/js/aoy-copy.js');

export function build(copy) {
  const en = {}, zh = {};
  // chat: [English, zh-CN, where it goes]
  for (const [key, value] of Object.entries(copy.chat)) { en[`chat.${key}`] = value[0]; zh[`chat.${key}`] = value[1]; }
  // web: English only in v2.0.0 ("The website only (English)")
  for (const [key, value] of Object.entries(copy.web)) en[`web.${key}`] = value;
  const body = JSON.stringify({ en, 'zh-CN': zh }, null, 1);
  return `// Generated by scripts/website-aoy-copy.mjs from docs/handoff-2026-11-09/agent-of-you-beta-2.0.0/copy.json. Do not edit.\n(function (root) { root.AoyCopy = ${body}; })(globalThis);\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = build(JSON.parse(readFileSync(source, 'utf8')));
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== next) { console.error('website/js/aoy-copy.js is out of date'); process.exit(1); }
  } else writeFileSync(target, next);
}
